"""Business KPIs and sales-trend aggregations."""

from __future__ import annotations

import pandas as pd

WEEKDAY_ORDER = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]


def kpis(df: pd.DataFrame) -> pd.Series:
    """Headline KPIs for the whole period."""
    orders = df.groupby("InvoiceNo")["Revenue"].sum()
    customers = df["CustomerID"].dropna()
    orders_per_customer = df.dropna(subset=["CustomerID"]).groupby("CustomerID")["InvoiceNo"].nunique()
    return pd.Series(
        {
            "total_revenue": round(df["Revenue"].sum(), 2),
            "orders": df["InvoiceNo"].nunique(),
            "customers": customers.nunique(),
            "products": df["StockCode"].nunique(),
            "countries": df["Country"].nunique(),
            "avg_order_value": round(orders.mean(), 2),
            "repeat_customer_rate_pct": round(100 * (orders_per_customer > 1).mean(), 2),
        }
    )


def monthly_revenue(df: pd.DataFrame) -> pd.DataFrame:
    """Revenue, orders, customers and AOV per month with MoM growth."""
    monthly = df.groupby("InvoiceMonth").agg(
        revenue=("Revenue", "sum"),
        orders=("InvoiceNo", "nunique"),
        customers=("CustomerID", "nunique"),
    )
    monthly["avg_order_value"] = monthly["revenue"] / monthly["orders"]
    monthly["revenue_mom_pct"] = monthly["revenue"].pct_change() * 100
    return monthly


def top_products(df: pd.DataFrame, n: int = 10, by: str = "Revenue") -> pd.DataFrame:
    """Top ``n`` products by revenue or quantity."""
    agg = df.groupby(["StockCode", "Description"], dropna=False).agg(
        Revenue=("Revenue", "sum"), Quantity=("Quantity", "sum"), Orders=("InvoiceNo", "nunique")
    )
    return agg.sort_values(by, ascending=False).head(n).reset_index()


def revenue_by_country(df: pd.DataFrame, n: int = 10) -> pd.DataFrame:
    """Top ``n`` countries by revenue with share of total."""
    agg = df.groupby("Country").agg(
        Revenue=("Revenue", "sum"), Customers=("CustomerID", "nunique"), Orders=("InvoiceNo", "nunique")
    )
    agg["Share_pct"] = 100 * agg["Revenue"] / agg["Revenue"].sum()
    return agg.sort_values("Revenue", ascending=False).head(n)


def weekday_hour_heatmap(df: pd.DataFrame) -> pd.DataFrame:
    """Order counts by weekday x hour of day."""
    orders = df.drop_duplicates("InvoiceNo")
    table = orders.pivot_table(index="Weekday", columns="Hour", values="InvoiceNo", aggfunc="count", fill_value=0)
    return table.reindex([d for d in WEEKDAY_ORDER if d in table.index])


def pareto_share(df: pd.DataFrame, top_fraction: float = 0.2) -> float:
    """Share of revenue (%) generated by the top ``top_fraction`` of customers."""
    per_customer = df.dropna(subset=["CustomerID"]).groupby("CustomerID")["Revenue"].sum().sort_values(ascending=False)
    k = max(1, round(len(per_customer) * top_fraction))
    return round(100 * per_customer.head(k).sum() / per_customer.sum(), 2)
